"""Generate worlds/resilientsync_{3,5}robots.wbt (so robot count, DEF names and geometry never drift).

    python webots_project/make_worlds.py
"""
import math
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from resilientsync_webots.robot_params import BASIC_TIME_STEP_MS, ROBOT_Z      # noqa: E402
from simulation.config import Config                                          # noqa: E402
from simulation.formation import make_formation                              # noqa: E402

COLORS = ["1.0 0.75 0.1", "0.2 0.45 0.85", "0.2 0.75 0.35", "0.8 0.3 0.7", "0.3 0.8 0.85", "0.9 0.5 0.2"]


def axis_angle(Rm):
    ang = math.acos(max(-1, min(1, (np.trace(Rm) - 1) / 2)))
    ax = np.array([Rm[2, 1] - Rm[1, 2], Rm[0, 2] - Rm[2, 0], Rm[1, 0] - Rm[0, 1]])
    ax = ax / np.linalg.norm(ax)
    return [*map(float, ax), float(ang)]


def viewpoint(cx, cy, eye):
    """ENU camera looks along its local +x axis, z up."""
    f = np.array([cx - eye[0], cy - eye[1], -eye[2]], float)
    f /= np.linalg.norm(f)
    yaw, pitch = math.atan2(f[1], f[0]), math.asin(-f[2])
    Rz = np.array([[math.cos(yaw), -math.sin(yaw), 0], [math.sin(yaw), math.cos(yaw), 0], [0, 0, 1]])
    Ry = np.array([[math.cos(pitch), 0, math.sin(pitch)], [0, 1, 0], [-math.sin(pitch), 0, math.cos(pitch)]])
    return axis_angle(Rz @ Ry)


def world_text(n: int) -> str:
    cfg = Config().copy(n_agents=n)
    xmin, xmax, ymin, ymax = cfg.world_x_min, cfg.world_x_max, cfg.world_y_min, cfg.world_y_max
    cx, cy, W, H = (xmin + xmax) / 2, (ymin + ymax) / 2, xmax - xmin, ymax - ymin
    offsets = make_formation(n)          # (n,2) body-frame slots; row 0 = leader
    # Camera rides with the leader (Mounted Shot): behind and above, so the whole wedge stays in view.
    # (The initial pose below is for the leader at the origin heading +x; Webots keeps that offset while following.)
    eye = (-7.0, 0.0, 6.0)
    vp = viewpoint(-1.0, 0.0, eye)
    L = []
    L.append("#VRML_SIM R2023b utf8")
    L.append(f"# GENERATED by webots_project/make_worlds.py -- {n} robots (1 leader + {n-1} followers). Do not hand-edit.")
    L.append("# STATUS: written without access to Webots -- NOT yet opened in a real Webots instance.")
    L.append('EXTERNPROTO "../protos/RSDiffDrive.proto"')
    L.append("")
    L.append("WorldInfo {")
    L.append('  title "ResilientSync 3D validation"')
    L.append('  coordinateSystem "ENU"')
    L.append(f"  basicTimeStep {BASIC_TIME_STEP_MS}")
    L.append("  contactProperties [")
    L.append('    ContactProperties { material1 "default" material2 "rs_caster" coulombFriction [ 0 ] }')
    L.append("  ]")
    L.append("}")
    L.append(f"Viewpoint {{ orientation {' '.join(f'{x:.5f}' for x in vp)} position {eye[0]} {eye[1]} {eye[2]} "
             f'follow "leader" followType "Mounted Shot" }}')
    L.append('Background { skyColor [ 0.62 0.76 0.92 ] }')
    L.append("DirectionalLight { direction -0.3 -0.5 -1 intensity 1.6 castShadows FALSE }")
    L.append("Solid {")
    L.append(f"  translation {cx} {cy} -0.05")
    L.append("  children [")
    L.append("    Shape { appearance PBRAppearance { baseColor 0.72 0.72 0.72 roughness 1 metalness 0 } "
             f"geometry Box {{ size {W} {H} 0.1 }} }}")
    L.append("  ]")
    L.append('  name "floor"')
    L.append(f"  boundingObject Box {{ size {W} {H} 0.1 }}")
    L.append("}")
    # slot markers (visual only: no boundingObject, no physics) -- moved by the coordinator
    for i in range(1, n):
        L.append(f"DEF SLOT_{i} Solid {{ translation 0 0 0.01 children [ Shape {{ appearance PBRAppearance {{ baseColor {COLORS[i % len(COLORS)]} "
                 f"transparency 0.4 roughness 1 metalness 0 }} geometry Cylinder {{ height 0.01 radius 0.12 }} }} ] name \"slot {i}\" }}")
    # robots: placed at the nominal formation; the coordinator re-places them at the seeded initial poses
    for i in range(n):
        x, y = float(offsets[i][0]), float(offsets[i][1])   # leader at origin, heading +x
        nm = "leader" if i == 0 else f"follower {i}"
        L.append(f'DEF RS_{i} RSDiffDrive {{ translation {x:.3f} {y:.3f} {ROBOT_Z} name "{nm}" '
                 f'controllerArgs [ "{i}" "{n}" ] bodyColor {COLORS[i % len(COLORS)]} }}')
    L.append("Robot {")
    L.append('  name "rs_coordinator"')
    L.append('  controller "rs_coordinator"')
    L.append("  supervisor TRUE")
    L.append("  children [ Emitter { name \"cmd_tx\" channel 1 } ]")
    L.append("}")
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    out = Path(__file__).resolve().parent / "worlds"
    out.mkdir(exist_ok=True)
    for n in (3, 5):
        p = out / f"resilientsync_{n}robots.wbt"
        p.write_text(world_text(n), encoding="utf-8")
        print("wrote", p)
